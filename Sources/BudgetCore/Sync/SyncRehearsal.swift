import CloudKit
import Darwin
import Foundation
import GRDB

/// The step 3 migration rehearsal (plan Task 8), run by the controller on a copy of the real database
/// (`swift run SyncRehearsal`). Offline throughout: nothing is sent anywhere.
///
/// 1. The database is opened read-only and copied twice with a backup (`original`, `copy`); the library, when
///    given, is copied too. The source is never opened for writing.
/// 2. `copy` is migrated (`createSync`, …) and backfilled; every table `original` has is compared with it,
///    value by value with each value's storage type (sync bookkeeping tables, if the source already had
///    them, aren't; `grdb_migrations` may only gain rows), and the tax figures of every stored year.
/// 3. The whole outgoing payload set is generated by the real engine pushing into an in-memory cloud
///    (`FakeCloud` with CloudKit's limits): counts per record type, bytes, the largest record, the documents
///    and their bytes. Every record is also built as the `CKRecord` the CloudKit transport would save
///    (offline): no value may sit outside its encrypted fields except a `CKAsset` of ciphertext.
/// 4. The payloads are applied into an empty migrated database through the checked pull
///    (`FiledYearSyncCheck`), timed, with the process's memory footprint sampled; row counts and tax figures
///    must come out the same.
public enum SyncRehearsal {
    public enum PathError: Error, Equatable, LocalizedError {
        case missing(String)
        case notAFolder(String)
        /// The app's own database: the rehearsal takes a copy, never the original.
        case appData(String)

        public var errorDescription: String? {
            switch self {
            case .missing(let path): return "No database file at \(path)"
            case .notAFolder(let path): return "\(path) is not a folder"
            case .appData(let path): return "Refusing the app's own database (\(path)): copy it first and pass the copy."
            }
        }
    }

    public struct TableComparison: Equatable, Sendable {
        public var table: String
        public var rows: Int
        public var identical: Bool
        /// Why it differs, or what was allowed (no values: names and counts only).
        public var note: String?
    }

    public struct Largest: Equatable, Sendable {
        public var recordType: String
        public var recordName: String
        /// Fields and assets.
        public var bytes: Int
    }

    public struct Apply: Equatable, Sendable {
        public var received = 0
        public var staged = 0
        public var unreadable = 0
        public var held = 0
        public var seconds: Double = 0
        /// The process's memory footprint when the apply started, and the highest sampled during it.
        public var footprintBeforeBytes: UInt64 = 0
        public var peakFootprintBytes: UInt64 = 0
        /// Synced tables whose row count differs between the migrated copy and the database applied into.
        public var rowCountMismatches: [String] = []
        /// Tax figures (every stored year) that differ between them.
        public var taxFiguresChanged = 0
    }

    public struct Report: Sendable {
        public var workFolder: URL
        public var migrationsRun: [String]
        public var backfilled: Int
        /// After the migration and backfill.
        public var tables: [TableComparison]
        /// Again after the payloads were generated (the push writes only sync bookkeeping).
        public var tablesAfterPayloads: [TableComparison]
        /// Tax figures that differ between the original and the migrated copy.
        public var taxFiguresChanged: Int
        public var records: Int
        public var recordsByType: [String: Int]
        public var bytesByType: [String: Int]
        /// Encrypted fields and names (`SyncWireRecord.size`).
        public var recordBytes: Int
        /// Asset fields (sealed files, large payloads).
        public var assetBytes: Int
        public var totalBytes: Int { recordBytes + assetBytes }
        public var largest: Largest?
        /// Records whose payload went as an encrypted asset (ruling R4).
        public var largePayloads: Int
        /// Sealed document files (`documentFile` records) and their ciphertext bytes.
        public var documents: Int
        public var documentBytes: Int
        /// `<recordType>.<field>` for any value outside the encrypted fields (must be empty).
        public var plaintextFields: [String]
        public var push: SyncPushReport
        public var pushSeconds: Double
        /// Changes still pending after the push (must be 0).
        public var pendingAfterPush: Int
        public var apply: Apply

        public var passed: Bool {
            tables.allSatisfy(\.identical) && tablesAfterPayloads.allSatisfy(\.identical) && taxFiguresChanged == 0
                && plaintextFields.isEmpty && pendingAfterPush == 0 && push.refused == 0
                && apply.staged == 0 && apply.unreadable == 0 && apply.held == 0
                && apply.rowCountMismatches.isEmpty && apply.taxFiguresChanged == 0
        }

        public var text: String { SyncRehearsal.text(self) }
    }

    /// `~` expanded and the path standardised, so the guard sees what is opened.
    public static func normalized(_ path: String) -> String {
        URL(fileURLWithPath: (path as NSString).expandingTildeInPath).standardizedFileURL.path
    }

    /// The database (a file that isn't the app's own) and the library (a folder; only read and copied, so it
    /// may be anywhere), normalised.
    @discardableResult
    public static func checkPaths(databasePath: String, libraryPath: String?,
                                  isAppData: (String) -> Bool = { TaxRegression.isAppData($0) }) throws -> (database: String, library: String?) {
        let fileManager = FileManager.default
        let database = normalized(databasePath)
        var isFolder: ObjCBool = false
        guard fileManager.fileExists(atPath: database, isDirectory: &isFolder), !isFolder.boolValue else { throw PathError.missing(database) }
        if isAppData(database) { throw PathError.appData(database) }
        var library: String?
        if let libraryPath {
            let path = normalized(libraryPath)
            guard fileManager.fileExists(atPath: path, isDirectory: &isFolder) else { throw PathError.missing(path) }
            guard isFolder.boolValue else { throw PathError.notAFolder(path) }
            library = path
        }
        return (database, library)
    }

    // MARK: Running

    public static func run(databasePath: String, libraryPath: String?, keep: Bool = false) async throws -> Report {
        let fileManager = FileManager.default
        let work = fileManager.temporaryDirectory.appendingPathComponent("SyncRehearsal-\(UUID().uuidString)", isDirectory: true)
        try fileManager.createDirectory(at: work, withIntermediateDirectories: true)
        defer { if !keep { try? fileManager.removeItem(at: work) } }

        // The copies: the source is opened read-only, once.
        let originalPath = work.appendingPathComponent("original.sqlite").path
        let copyPath = work.appendingPathComponent("copy.sqlite").path
        var readOnly = Configuration()
        readOnly.readonly = true
        do {
            let source = try DatabaseQueue(path: databasePath, configuration: readOnly)
            let original = try DatabaseQueue(path: originalPath)
            try source.backup(to: original)
            let copy = try DatabaseQueue(path: copyPath)
            try original.backup(to: copy)
            try source.close()
            try original.close()
            try copy.close()
        }
        var library: URL?
        if let libraryPath {
            let root = work.appendingPathComponent("Library", isDirectory: true)
            try fileManager.copyItem(at: URL(fileURLWithPath: libraryPath, isDirectory: true), to: root)
            library = root
        }
        let original = try DatabaseQueue(path: originalPath, configuration: readOnly)
        defer { try? original.close() }

        // Migrate and backfill the copy.
        let manager = try DatabaseManager(path: copyPath)
        let copy = manager.dbQueue
        defer { try? copy.close() }
        let migrationsRun = try manager.migrationStatus().pending
        try manager.migrate()
        let backfilled = try await copy.write { db in try SyncRecordStore.backfill(db: db) }
        let tables = try compare(original, copy)
        let originalFigures = try await original.read { db in try TaxFigures.snapshot(db: db) }
        let copyFigures = try await copy.read { db in try TaxFigures.snapshot(db: db) }
        let taxFiguresChanged = TaxFigures.changes(from: originalFigures, to: copyFigures).count

        // The outgoing payload set, generated by the engine into an in-memory cloud with CloudKit's limits.
        let cloud = FakeCloud(recordSizeLimit: CloudKitRecordMapping.recordSizeLimit, limits: CloudKitRecordMapping.operationLimits)
        let sender = SyncEngineCore(db: copy, transport: cloud, device: SyncDevice(id: "rehearsal-sender", name: "Rehearsal"),
                                    documents: library.map { SyncDocumentFiles(root: $0, policy: .lazy) })
        let pushStart = Date()
        let push = try await sender.pushPending()
        let pushSeconds = Date().timeIntervalSince(pushStart)
        let pendingAfterPush = try await copy.read { db in try SyncChangeTracker.pending(db: db).count }
        let tablesAfterPayloads = try compare(original, copy)

        let stored = await cloud.storedRecords()
        var recordsByType: [String: Int] = [:]
        var bytesByType: [String: Int] = [:]
        var recordBytes = 0
        var assetBytes = 0
        var largest: Largest?
        var largePayloads = 0
        var documents = 0
        var documentBytes = 0
        for wire in stored {
            let assets = wire.assets.values.reduce(0) { $0 + $1.count }
            recordsByType[wire.recordType, default: 0] += 1
            bytesByType[wire.recordType, default: 0] += wire.size + assets
            recordBytes += wire.size
            assetBytes += assets
            if wire.size + assets > largest?.bytes ?? -1 {
                largest = Largest(recordType: wire.recordType, recordName: wire.recordName, bytes: wire.size + assets)
            }
            if wire.recordType == SyncDocumentFile.recordType {
                documents += 1
                documentBytes += assets
            } else if !wire.assets.isEmpty {
                largePayloads += 1
            }
        }
        var plaintext = Set(await cloud.unencryptedFieldNames)
        plaintext.formUnion(try plaintextFields(in: stored, assetDirectory: work.appendingPathComponent("Assets", isDirectory: true)))

        // Applied into an empty migrated database through the checked pull.
        let receiverManager = try DatabaseManager(path: work.appendingPathComponent("receiver.sqlite").path)
        try receiverManager.migrate()
        let receiver = receiverManager.dbQueue
        defer { try? receiver.close() }
        let receiving = SyncEngineCore(db: receiver, transport: cloud, device: SyncDevice(id: "rehearsal-receiver", name: "Rehearsal receiver"),
                                       documents: SyncDocumentFiles(root: work.appendingPathComponent("ReceiverLibrary", isDirectory: true), policy: .lazy))
        var apply = Apply()
        let sampler = FootprintSampler()
        apply.footprintBeforeBytes = FootprintSampler.current()
        sampler.start()
        let applyStart = Date()
        let pulled = try await receiving.pull()
        apply.seconds = Date().timeIntervalSince(applyStart)
        apply.peakFootprintBytes = sampler.stop()
        apply.received = pulled.received
        apply.staged = pulled.staged
        apply.unreadable = pulled.unreadable
        apply.held = pulled.held
        for table in SyncSchema.tables {
            let sql = "SELECT COUNT(*) FROM \(quoted(table.name))"
            let sent = try await copy.read { db in try Int.fetchOne(db, sql: sql) ?? 0 }
            let arrived = try await receiver.read { db in try Int.fetchOne(db, sql: sql) ?? 0 }
            if sent != arrived { apply.rowCountMismatches.append("\(table.name): \(sent) sent, \(arrived) there") }
        }
        let receiverFigures = try await receiver.read { db in try TaxFigures.snapshot(db: db) }
        apply.taxFiguresChanged = TaxFigures.changes(from: copyFigures, to: receiverFigures).count

        return Report(workFolder: work, migrationsRun: migrationsRun, backfilled: backfilled, tables: tables,
                      tablesAfterPayloads: tablesAfterPayloads, taxFiguresChanged: taxFiguresChanged, records: stored.count,
                      recordsByType: recordsByType, bytesByType: bytesByType, recordBytes: recordBytes, assetBytes: assetBytes,
                      largest: largest, largePayloads: largePayloads, documents: documents, documentBytes: documentBytes,
                      plaintextFields: plaintext.sorted(), push: push, pushSeconds: pushSeconds, pendingAfterPush: pendingAfterPush,
                      apply: apply)
    }

    // MARK: Comparing tables

    private static func compare(_ original: DatabaseQueue, _ copy: DatabaseQueue) throws -> [TableComparison] {
        try original.read { a in try copy.read { b in try compareTables(original: a, copy: b) } }
    }

    /// Every table `original` has (and `sqlite_sequence`'s rows for them), compared with `copy`: the columns
    /// `original` has, row by row in rowid order, each value with its storage type (`typeof`), so a changed
    /// byte, a REAL off in its last bit or a TEXT become a BLOB all differ. Columns and tables a migration
    /// added aren't compared; `grdb_migrations` may only gain rows; sync bookkeeping tables (`sync…`) a
    /// source already had are listed but not compared (the backfill writes them).
    static func compareTables(original: Database, copy: Database) throws -> [TableComparison] {
        let names = try String.fetchAll(original, sql: "SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name")
        var result: [TableComparison] = []
        for name in names {
            guard try copy.tableExists(name) else {
                result.append(TableComparison(table: name, rows: 0, identical: false, note: "missing from the copy"))
                continue
            }
            if name.hasPrefix("sync") {
                let rows = try Int.fetchOne(original, sql: "SELECT COUNT(*) FROM \(quoted(name))") ?? 0
                result.append(TableComparison(table: name, rows: rows, identical: true, note: "sync bookkeeping (not compared)"))
                continue
            }
            if name == "grdb_migrations" {
                let before = try String.fetchAll(original, sql: "SELECT identifier FROM grdb_migrations ORDER BY rowid")
                let after = try String.fetchAll(copy, sql: "SELECT identifier FROM grdb_migrations ORDER BY rowid")
                let appended = Array(after.prefix(before.count)) == before
                result.append(TableComparison(table: name, rows: before.count, identical: appended,
                                              note: appended ? "\(after.count - before.count) appended" : "existing migrations changed"))
                continue
            }
            let where_ = name == "sqlite_sequence" ? " WHERE name IN (SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sync%')" : ""
            let columns = try original.columns(in: name).map(\.name)
            let select = columns.map { "typeof(\(quoted($0))), \(quoted($0))" }.joined(separator: ", ")
            let sqlText = try String.fetchOne(original, sql: "SELECT sql FROM sqlite_master WHERE name = ?", arguments: [name]) ?? ""
            let order = name == "sqlite_sequence" ? "name"
                : sqlText.uppercased().contains("WITHOUT ROWID") ? columns.map(quoted).joined(separator: ", ") : "rowid"
            let sql = "SELECT \(select) FROM \(quoted(name))\(where_) ORDER BY \(order)"
            let a = try Row.fetchCursor(original, sql: sql)
            let b = try Row.fetchCursor(copy, sql: sql)
            var rows = 0
            var note: String?
            while true {
                let left = try a.next()
                let right = try b.next()
                if left == nil, right == nil { break }
                rows += 1
                guard let left, let right else {
                    note = left == nil ? "the copy has more rows" : "the copy has fewer rows"
                    break
                }
                if !sameValues(left, right) {
                    note = "row \(rows) differs"
                    break
                }
            }
            result.append(TableComparison(table: name, rows: rows, identical: note == nil, note: note))
        }
        return result
    }

    /// Value by value; a REAL compares by its bits.
    private static func sameValues(_ left: Row, _ right: Row) -> Bool {
        guard left.count == right.count else { return false }
        for index in 0..<left.count {
            let a: DatabaseValue = left[index]
            let b: DatabaseValue = right[index]
            switch (a.storage, b.storage) {
            case (.null, .null): continue
            case (.int64(let x), .int64(let y)) where x == y: continue
            case (.double(let x), .double(let y)) where x.bitPattern == y.bitPattern: continue
            case (.string(let x), .string(let y)) where Array(x.utf8) == Array(y.utf8): continue
            case (.blob(let x), .blob(let y)) where x == y: continue
            default: return false
            }
        }
        return true
    }

    private static func quoted(_ identifier: String) -> String {
        "\"" + identifier.replacingOccurrences(of: "\"", with: "\"\"") + "\""
    }

    // MARK: Plaintext

    /// `<recordType>.<field>` for every value of `wires` that would reach CloudKit outside its encrypted
    /// values: an unencrypted field, or any plain key of the `CKRecord` the transport builds that isn't a
    /// `CKAsset`. Built offline; the asset files go in `assetDirectory`, removed afterwards.
    static func plaintextFields(in wires: [SyncWireRecord], assetDirectory: URL) throws -> [String] {
        defer { try? FileManager.default.removeItem(at: assetDirectory) }
        var found = Set<String>()
        for wire in wires {
            if !wire.unencryptedFields.isEmpty {
                for field in wire.unencryptedFields.keys { found.insert(wire.recordType + "." + field) }
                continue
            }
            let folder = assetDirectory.appendingPathComponent(UUID().uuidString, isDirectory: true)
            let record = try CloudKitRecordMapping.record(from: wire, systemFields: nil, assetDirectory: folder)
            for key in Set(record.allKeys()).subtracting(record.encryptedValues.allKeys()) where !(record[key] is CKAsset) {
                found.insert(wire.recordType + "." + key)
            }
            try? FileManager.default.removeItem(at: folder)
        }
        return found.sorted()
    }

    // MARK: The report

    static func text(_ report: Report) -> String {
        func mb(_ bytes: Int) -> String { String(format: "%.2f MB", Double(bytes) / 1_000_000) }
        func mb(_ bytes: UInt64) -> String { mb(Int(bytes)) }
        var lines: [String] = []
        lines.append("# Sync migration rehearsal (step 3)")
        lines.append("")
        lines.append("Result: **\(report.passed ? "PASSED" : "FAILED")**")
        lines.append("")
        lines.append("## Migration")
        lines.append("- Migrations run on the copy: \(report.migrationsRun.isEmpty ? "none" : report.migrationsRun.joined(separator: ", "))")
        lines.append("- Rows backfilled with a sync identity: \(report.backfilled)")
        let differing = report.tables.filter { !$0.identical }
        lines.append("- Existing tables compared: \(report.tables.count), identical: \(report.tables.count - differing.count)")
        for table in differing { lines.append("  - DIFFERS \(table.table): \(table.note ?? "")") }
        let differingAfter = report.tablesAfterPayloads.filter { !$0.identical }
        lines.append("- Identical again after generating the payloads: \(differingAfter.isEmpty ? "yes" : "NO")")
        for table in differingAfter { lines.append("  - DIFFERS \(table.table): \(table.note ?? "")") }
        lines.append("- Tax figures (every stored year) changed by the migration: \(report.taxFiguresChanged)")
        lines.append("")
        lines.append("## Outgoing payloads (generated offline)")
        lines.append("- Records: \(report.records) · total \(mb(report.totalBytes)) (fields \(mb(report.recordBytes)), assets \(mb(report.assetBytes)))")
        if let largest = report.largest { lines.append("- Largest record: \(largest.recordType), \(largest.bytes) bytes") }
        lines.append("- Payloads sent as encrypted assets (> \(SyncEngineCore.largePayloadThreshold) bytes): \(report.largePayloads)")
        lines.append("- Documents: \(report.documents) sealed files, \(mb(report.documentBytes)); document records: \(report.recordsByType["document"] ?? 0)")
        lines.append("- Values outside encrypted fields: \(report.plaintextFields.isEmpty ? "none" : report.plaintextFields.joined(separator: ", "))")
        lines.append("- Push: saved \(report.push.saved), refused \(report.push.refused), as assets \(report.push.asAssets), files sealed \(report.push.documentsSealed), deferred \(report.push.documentsDeferred); \(String(format: "%.1f", report.pushSeconds)) s; still pending \(report.pendingAfterPush)")
        lines.append("")
        lines.append("| Record type | Records | Bytes |")
        lines.append("|---|---:|---:|")
        for (type, count) in report.recordsByType.sorted(by: { $0.key < $1.key }) {
            lines.append("| \(type) | \(count) | \(report.bytesByType[type] ?? 0) |")
        }
        lines.append("")
        lines.append("## Apply into an empty database (checked pull)")
        lines.append("- Received \(report.apply.received) · staged \(report.apply.staged) · unreadable \(report.apply.unreadable) · held \(report.apply.held)")
        lines.append("- Time: \(String(format: "%.2f", report.apply.seconds)) s")
        lines.append("- Memory footprint: \(mb(report.apply.footprintBeforeBytes)) before, \(mb(report.apply.peakFootprintBytes)) peak (+\(mb(report.apply.peakFootprintBytes &- min(report.apply.peakFootprintBytes, report.apply.footprintBeforeBytes))))")
        lines.append("- Row counts that differ: \(report.apply.rowCountMismatches.isEmpty ? "none" : report.apply.rowCountMismatches.joined(separator: "; "))")
        lines.append("- Tax figures that differ from the copy: \(report.apply.taxFiguresChanged)")
        lines.append("")
        return lines.joined(separator: "\n")
    }
}

/// Samples the process's memory footprint (`phys_footprint`, what Activity Monitor shows) every 20 ms.
final class FootprintSampler: @unchecked Sendable {
    private let lock = NSLock()
    private var peak: UInt64 = 0
    private var timer: DispatchSourceTimer?

    static func current() -> UInt64 {
        var info = task_vm_info_data_t()
        var count = mach_msg_type_number_t(MemoryLayout<task_vm_info_data_t>.size / MemoryLayout<natural_t>.size)
        let result = withUnsafeMutablePointer(to: &info) { pointer in
            pointer.withMemoryRebound(to: integer_t.self, capacity: Int(count)) { task_info(mach_task_self_, task_flavor_t(TASK_VM_INFO), $0, &count) }
        }
        return result == KERN_SUCCESS ? info.phys_footprint : 0
    }

    private func sample() {
        let now = Self.current()
        lock.lock()
        peak = max(peak, now)
        lock.unlock()
    }

    func start() {
        sample()
        let timer = DispatchSource.makeTimerSource(queue: DispatchQueue.global(qos: .utility))
        timer.schedule(deadline: .now(), repeating: .milliseconds(20))
        timer.setEventHandler { [weak self] in self?.sample() }
        timer.resume()
        self.timer = timer
    }

    func stop() -> UInt64 {
        timer?.cancel()
        timer = nil
        sample()
        lock.lock()
        defer { lock.unlock() }
        return peak
    }
}
