/// Samples the process's memory footprint (`phys_footprint`, what Activity Monitor shows) every 20 ms.
final class FootprintSampler: Sendable {
    private let peak = OSAllocatedUnfairLock(initialState: UInt64(0))
    private let sampling = OSAllocatedUnfairLock<Task<Void, Never>?>(initialState: nil)

    static func current() -> UInt64 {
        // `task_self_trap` rather than the C global `mach_task_self_` (not concurrency-safe in Swift 6); the
        // send right it adds is given back.
        let task = task_self_trap()
        defer { mach_port_deallocate(task, task) }
        var info = task_vm_info_data_t()
        var count = mach_msg_type_number_t(MemoryLayout<task_vm_info_data_t>.size / MemoryLayout<natural_t>.size)
        let result = withUnsafeMutablePointer(to: &info) { pointer in
            pointer.withMemoryRebound(to: integer_t.self, capacity: Int(count)) { task_info(task, task_flavor_t(TASK_VM_INFO), $0, &count) }
        }
        return result == KERN_SUCCESS ? info.phys_footprint : 0
    }

    private func sample() {
        let now = Self.current()
        peak.withLock { $0 = max($0, now) }
    }

    func start() {
        sample()
        let task = Task.detached(priority: .utility) { [self] in
            while !Task.isCancelled {
                sample()
                try? await Task.sleep(for: .milliseconds(20))
            }
        }
        sampling.withLock { $0 = task }
    }

    func stop() -> UInt64 {
        sampling.withLock { $0?.cancel(); $0 = nil }
        sample()
        return peak.withLock { $0 }
    }
}
